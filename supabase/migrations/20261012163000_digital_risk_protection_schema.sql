-- Enable required core PostgreSQL extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =============================================================================
-- 1. TABLE: brand_profiles
-- Enterprise brand entities monitored across digital channels
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.brand_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    industry VARCHAR(100),
    website VARCHAR(255),
    description TEXT,
    keywords TEXT,           -- Comma-separated or JSON string of targeted keywords
    aliases TEXT,            -- Comma-separated or JSON string of known brand aliases
    logo_url VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_brand_profiles_name ON public.brand_profiles (name);

-- =============================================================================
-- 2. TABLE: official_social_assets
-- Whitelisted official social media handles for zero false-positive immunity
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.official_social_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    platform VARCHAR(50) NOT NULL,       -- e.g., 'Instagram', 'X', 'Facebook', 'LinkedIn'
    handle VARCHAR(255) NOT NULL,
    url VARCHAR(500),
    verified_badge BOOLEAN NOT NULL DEFAULT true,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_official_social_brand_id ON public.official_social_assets (brand_id);
CREATE INDEX IF NOT EXISTS idx_official_social_handle ON public.official_social_assets (platform, handle);

-- =============================================================================
-- 3. TABLE: official_applications
-- Whitelisted mobile applications & publisher identities
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.official_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    app_name VARCHAR(255) NOT NULL,
    package_id VARCHAR(255) NOT NULL,    -- e.g., 'com.novapay.app'
    store VARCHAR(100) NOT NULL,         -- e.g., 'Google Play', 'Apple App Store'
    store_url VARCHAR(500),
    publisher_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_official_apps_brand_id ON public.official_applications (brand_id);
CREATE INDEX IF NOT EXISTS idx_official_apps_package ON public.official_applications (store, package_id);

-- =============================================================================
-- 4. TABLE: social_profile_records
-- Ingested external candidate social accounts monitored for brand abuse
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.social_profile_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    platform VARCHAR(50) NOT NULL,
    username VARCHAR(255) NOT NULL,
    display_name VARCHAR(255),
    profile_url VARCHAR(500),
    bio TEXT,
    follower_count BIGINT DEFAULT 0,
    account_created_at VARCHAR(100),
    data_source VARCHAR(100) NOT NULL DEFAULT 'synthetic_demo', -- 'synthetic_demo', 'csv_upload', 'api'
    raw_data TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_social_records_brand_id ON public.social_profile_records (brand_id);
CREATE INDEX IF NOT EXISTS idx_social_records_platform_user ON public.social_profile_records (platform, username);

-- =============================================================================
-- 5. TABLE: app_listing_records
-- Ingested external app store listings & third-party APK mirrors
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.app_listing_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    app_name VARCHAR(255) NOT NULL,
    package_id VARCHAR(255) NOT NULL,
    developer_name VARCHAR(255) NOT NULL,
    store_name VARCHAR(100) NOT NULL,
    store_url VARCHAR(500),
    description TEXT,
    icon_url VARCHAR(500),
    permissions TEXT,
    data_source VARCHAR(100) NOT NULL DEFAULT 'synthetic_demo',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_app_records_brand_id ON public.app_listing_records (brand_id);
CREATE INDEX IF NOT EXISTS idx_app_records_store_package ON public.app_listing_records (store_name, package_id);

-- =============================================================================
-- 6. TABLE: findings
-- Security incident queue tracking detected impersonations and anomalies
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    asset_type VARCHAR(50) NOT NULL,    -- 'social', 'app'
    record_id BIGINT,
    asset_name VARCHAR(255) NOT NULL,
    platform_or_store VARCHAR(100) NOT NULL,
    source_url VARCHAR(500),
    risk_score NUMERIC(5, 2) NOT NULL DEFAULT 0.0 CHECK (risk_score >= 0.0 AND risk_score <= 100.0),
    risk_category VARCHAR(50) NOT NULL, -- 'Critical', 'High', 'Medium', 'Low', 'Safe'
    detection_reasons_json TEXT,        -- JSON array string of explainable detection triggers
    evidence_snippets_json TEXT,        -- JSON object string with algorithmic score breakdown
    matched_official_asset_json TEXT,   -- JSON object string
    similarity_details_json TEXT,       -- JSON object string with Levenshtein & Jaccard metrics
    review_status VARCHAR(50) NOT NULL DEFAULT 'unreviewed' CHECK (review_status IN ('unreviewed', 'reviewed', 'false_positive', 'escalated', 'resolved')),
    reviewer_notes TEXT,
    recommended_action VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_findings_brand_id ON public.findings (brand_id);
CREATE INDEX IF NOT EXISTS idx_findings_brand_risk ON public.findings (brand_id, risk_category);
CREATE INDEX IF NOT EXISTS idx_findings_brand_status ON public.findings (brand_id, review_status);
CREATE INDEX IF NOT EXISTS idx_findings_risk_score ON public.findings (risk_score DESC);
CREATE INDEX IF NOT EXISTS idx_findings_created_at ON public.findings (created_at DESC);

-- =============================================================================
-- 7. TABLE: scan_histories
-- Telemetry logs for detection engine sweeps and batch analysis
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.scan_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    scan_type VARCHAR(50) NOT NULL DEFAULT 'full', -- 'social', 'app', 'full'
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    status VARCHAR(50) NOT NULL DEFAULT 'completed', -- 'completed', 'in_progress', 'failed'
    records_processed INT NOT NULL DEFAULT 0,
    alerts_generated INT NOT NULL DEFAULT 0,
    excluded_assets_count INT NOT NULL DEFAULT 0,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_scans_brand_id ON public.scan_histories (brand_id);
CREATE INDEX IF NOT EXISTS idx_scans_started_at ON public.scan_histories (started_at DESC);
CREATE INDEX IF NOT EXISTS idx_scans_status ON public.scan_histories (status);

-- =============================================================================
-- 8. TABLE: review_feedback
-- SOC analyst human-in-the-loop audit actions & triage history
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.review_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL REFERENCES public.findings(id) ON DELETE CASCADE,
    user_action VARCHAR(50) NOT NULL, -- 'status_changed_to_reviewed', 'status_changed_to_escalated', etc.
    is_false_positive BOOLEAN NOT NULL DEFAULT false,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_review_feedback_finding_id ON public.review_feedback (finding_id);

-- =============================================================================
-- 9. TABLE: audit_logs
-- Immutable compliance and security event trail
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT REFERENCES public.brand_profiles(id) ON DELETE CASCADE,
    event_type VARCHAR(100) NOT NULL, -- 'OFFICIAL_ASSET_EXCLUDED', 'BRAND_CREATED', etc.
    details TEXT,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_brand_id ON public.audit_logs (brand_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_timestamp ON public.audit_logs (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_event_type ON public.audit_logs (event_type);

-- =============================================================================
-- AUTOMATIC TIMESTAMPS TRIGGER FUNCTION
-- =============================================================================
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'set_brand_profiles_updated_at') THEN
        CREATE TRIGGER set_brand_profiles_updated_at
            BEFORE UPDATE ON public.brand_profiles
            FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'set_findings_updated_at') THEN
        CREATE TRIGGER set_findings_updated_at
            BEFORE UPDATE ON public.findings
            FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();
    END IF;
END $$;

